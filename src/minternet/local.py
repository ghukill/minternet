"""Local target: one container per site behind an nginx proxy on this machine.

Mirrors exe.dev, where each site gets its own hostname and HTTPS proxy: here
each site gets http://<site>.<tld> and the proxy routes by Host header.
"""

from __future__ import annotations

import urllib.error
import urllib.request
from pathlib import Path

import click

from . import docker
from .config import Project, Site
from .runner import Runner, Shell

STATE_DIR = ".minternet"


class LocalTarget:
    name = "local"

    def __init__(self, project: Project, runner: Runner):
        self.project = project
        self.runner = runner
        self.shell = Shell(runner)
        self.prefix = project.settings.prefix

    # -- names -------------------------------------------------------------
    @property
    def network(self) -> str:
        return self.prefix

    @property
    def proxy_container(self) -> str:
        return f"{self.prefix}-proxy"

    @property
    def proxy_conf_dir(self) -> Path:
        return self.project.root / STATE_DIR / "proxy"

    # -- deploy ------------------------------------------------------------
    def deploy(self, sites: list[Site]) -> None:
        self._ensure_network()
        for site in sites:
            click.secho(f"==> {site.name} (local)", bold=True)
            docker.build(self.shell, site, str(site.path))
            docker.replace_container(
                self.shell,
                site,
                prefix=self.prefix,
                env=self.project.runtime_env(site, "local"),
                network=self.network,
            )
            docker.wait_healthy(self.shell, site)
        self._restart_proxy()
        for site in sites:
            click.echo(f"Done. {site.url(self.project.settings, 'local')}")
        self._hosts_hint(sites)

    def remove(self, sites: list[Site]) -> None:
        for site in sites:
            self.shell.run(["docker", "rm", "-f", site.container], check=False)
        if not self.runner.dry_run and not self._running_sites():
            click.echo("No sites running; removing proxy and network.")
            self.shell.run(["docker", "rm", "-f", self.proxy_container], check=False)
            self.shell.run(["docker", "network", "rm", self.network], check=False)

    # -- inspect -----------------------------------------------------------
    def status(self, sites: list[Site]) -> list[dict[str, str]]:
        rows = []
        for site in sites:
            state = docker.container_state(self.shell, site.container)
            container = "absent" if state is None else f"{state[0]} ({state[1]})"
            rows.append(
                {
                    "site": site.name,
                    "url": site.url(self.project.settings, "local"),
                    "container": container,
                    "http": self._probe(site) if state else "-",
                }
            )
        return rows

    def logs(self, site: Site, follow: bool) -> None:
        cmd = ["docker", "logs", "--tail", "100"]
        if follow:
            cmd.append("-f")
        self.shell.run([*cmd, site.container], check=False)

    # -- internals ---------------------------------------------------------
    def _running_sites(self) -> list[str]:
        result = self.shell.query(
            [
                "docker", "ps", "-a",
                "--filter", f"label={docker.LABEL_PROJECT}={self.prefix}",
                "--format", f'{{{{.Label "{docker.LABEL_SITE}"}}}}',
            ],
            check=False,
        )
        return [line for line in result.stdout.splitlines() if line.strip()]

    def _ensure_network(self) -> None:
        exists = self.shell.query(["docker", "network", "inspect", self.network], check=False)
        if exists.returncode != 0:
            self.shell.run(["docker", "network", "create", self.network])

    def proxy_config(self) -> str:
        """nginx config routing <site>.<tld> to each site's container."""
        tld = self.project.settings.local_tld
        blocks = [
            "# Generated by `minternet deploy -t local`; do not edit.",
            "resolver 127.0.0.11 valid=10s ipv6=off;",
            "",
        ]
        for site in self.project.sites:
            blocks.append(
                f"""server {{
    listen 80;
    server_name {site.name}.{tld};
    location / {{
        # A variable forces per-request DNS, so nginx starts even when this
        # site's container isn't running (requests then get a 502).
        set $upstream http://{site.container}:{site.port};
        proxy_pass $upstream;
        proxy_set_header Host $http_host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $http_connection;
    }}
}}
"""
            )
        blocks.append(
            """server {
    listen 80 default_server;
    server_name _;
    return 404 "Unknown minternet site\\n";
}
"""
        )
        return "\n".join(blocks)

    def _restart_proxy(self) -> None:
        conf_path = self.proxy_conf_dir / "default.conf"
        click.echo(f"Writing {conf_path.relative_to(self.project.root)}")
        if not self.runner.dry_run:
            self.proxy_conf_dir.mkdir(parents=True, exist_ok=True)
            conf_path.write_text(self.proxy_config())
        self.shell.run(["docker", "rm", "-f", self.proxy_container], check=False)
        self.shell.run(
            [
                "docker", "run", "-d",
                "--name", self.proxy_container,
                "--restart", "unless-stopped",
                "--label", f"{docker.LABEL_PROJECT}-proxy={self.prefix}",
                "--network", self.network,
                "-p", f"{self.project.settings.local_http_port}:80",
                "-v", f"{self.proxy_conf_dir}:/etc/nginx/conf.d:ro",
                "nginx:alpine",
            ]
        )

    def _probe(self, site: Site) -> str:
        """GET /healthz through the proxy using a Host header (no /etc/hosts needed)."""
        port = self.project.settings.local_http_port
        request = urllib.request.Request(
            f"http://127.0.0.1:{port}/healthz",
            headers={"Host": site.local_host(self.project.settings)},
        )
        try:
            with urllib.request.urlopen(request, timeout=5) as response:
                return str(response.status)
        except urllib.error.HTTPError as exc:
            return str(exc.code)
        except (urllib.error.URLError, OSError) as exc:
            return f"error: {getattr(exc, 'reason', exc)}"

    def _hosts_hint(self, sites: list[Site]) -> None:
        from .hosts import missing_hosts

        missing = missing_hosts(self.project, sites)
        if missing:
            click.echo()
            click.secho("Some hostnames are not in /etc/hosts. Run `minternet hosts` for details.", fg="yellow")
